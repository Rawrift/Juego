const DICTS = { es: ES, en: EN, pt: PT };
const KEY = 'riftcargo.lang';

function detect() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved && DICTS[saved]) return saved;
  } catch {}
  const nav = (navigator.language || 'es').slice(0, 2).toLowerCase();
  return DICTS[nav] ? nav : 'en';
}

export let lang = detect();
export function setLang(l) {
  lang = DICTS[l] ? l : 'es';
  try { localStorage.setItem(KEY, lang); } catch {}
  document.documentElement.lang = lang;
}
document.documentElement.lang = lang;

export function t(key, vars) {
  let s = DICTS[lang][key] ?? ES[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

const nf = () => new Intl.NumberFormat(lang === 'en' ? 'en-US' : lang === 'pt' ? 'pt-BR' : 'es-AR');
export const num = (n) => nf().format(Math.round(n));
export const money = (n) => `${n < 0 ? '−' : ''}$${num(Math.abs(n))}`;
export const pct = (k) => `${new Intl.NumberFormat(lang === 'en' ? 'en-US' : 'es-AR', { maximumFractionDigits: 1 }).format(k * 100)}%`;
export function dur(sec) {
  sec = Math.max(0, Math.round(sec));
  if (sec >= 3600) return `${Math.floor(sec / 3600)} h ${Math.floor((sec % 3600) / 60)} min`;
  return `${Math.floor(sec / 60)}:${String(sec % 60).padStart(2, '0')}`;
}
