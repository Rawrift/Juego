/** Texto traducido. Las variables van entre llaves: t('hud.level', { n: 3 }). */
export function t(key, vars) {
  let s = UI[lang]?.[key] ?? UI.es[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

